const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
const merge = (base, extra) => {
  const out = { ...base };
  for (const [k, v] of Object.entries(extra)) out[k] = isObj(v) && isObj(base[k]) ? merge(base[k], v) : v;
  return out;
};
const DICTS = { en: merge(en, PRO.en), ro: merge(ro, PRO.ro) };
export const LANGS = ['en', 'ro'];

const lookup = (dict, key) => key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict);

const I18nContext = createContext(null);

function initialLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* storage blocked */
  }
  return navigator.language?.toLowerCase().startsWith('ro') ? 'ro' : 'en';
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);

  const setLang = useCallback((l) => {
    if (!LANGS.includes(l)) return;
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem('lang', l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key, vars) => {
      let s = lookup(DICTS[lang], key) ?? lookup(DICTS.en, key);
      if (typeof s !== 'string') return s ?? key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
      return s;
    },
    [lang],
  );

  /** Translate an API error (code from the server) into a sentence. */
  const tErr = useCallback(
    (err) => {
      const code = err?.code;
      const msg = code && lookup(DICTS[lang].errors, code);
      if (typeof msg === 'string') return t(`errors.${code}`, err.data ?? {});
      return code === 'network' ? t('errors.network') : t('errors.generic');
    },
    [lang, t],
  );

  const locale = lang === 'ro' ? 'ro-RO' : 'en-GB';
  const value = useMemo(() => ({ lang, setLang, t, tErr, locale }), [lang, setLang, t, tErr, locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
